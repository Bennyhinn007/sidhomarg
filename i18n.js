// Remember the English text that is already in the page.
const EN = {};
document.querySelectorAll('[data-i18n]').forEach(el => {
  const k = el.dataset.i18n;
  if (!(k in EN)) EN[k] = el.innerHTML;
});

let lang = 'en';

function setLang(l) {
  lang = l;
  const dict = l === 'kn' ? KN : EN;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const t = dict[el.dataset.i18n];
    if (t !== undefined) el.innerHTML = t;
  });
  document.documentElement.lang = l;
  document.querySelectorAll('.lang button').forEach(b =>
    b.setAttribute('aria-pressed', String(b.dataset.lang === l)));
  try { localStorage.setItem('lang', l); } catch (e) {}
  if (typeof moveIndicator === 'function') moveIndicator();
}

document.querySelectorAll('.lang button').forEach(b =>
  b.addEventListener('click', () => setLang(b.dataset.lang)));

document.querySelectorAll('form[data-done]').forEach(f =>
  f.addEventListener('submit', e => {
    e.preventDefault();
    const btn = f.querySelector('button');
    btn.removeAttribute('data-i18n');
    btn.textContent = DONE[lang][f.dataset.done];
  }));

let saved = 'en';
try { saved = localStorage.getItem('lang') || 'en'; } catch (e) {}
if (saved === 'kn') setLang('kn');
